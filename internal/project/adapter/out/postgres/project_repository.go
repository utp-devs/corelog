type ProjectRepository struct {
	db *sqlx.DB
}

func NewProjectRepository(db *sqlx.DB) *ProjectRepository {
	return &ProjectRepository{db: db}
}

var _ port.Repository = (*ProjectRepository)(nil)
var _ port.ProjectCreationRepository = (*ProjectRepository)(nil)

// exec returns the transaction bound to ctx, or the pool when there is none.
func (r *ProjectRepository) exec(ctx context.Context) sqlx.ExtContext {
	return database.Executor(ctx, r.db)
}

const insertProjectQuery = `
	INSERT INTO projects (organization_id, key, name, description, type, template, lead_id, visibility,
	                      color, icon, default_assignee_policy, next_issue_number, archived_at, deleted_at,
	                      created_at, updated_at)
	VALUES (:organization_id, :key, :name, :description, :type, :template, :lead_id, :visibility,
	        :color, :icon, :default_assignee_policy, :next_issue_number, :archived_at, :deleted_at,
	        :created_at, :updated_at)
	RETURNING id`

func (r *ProjectRepository) Save(ctx context.Context, p *domain.Project) error {
	id, err := database.InsertReturningID(ctx, r.exec(ctx), insertProjectQuery, fromDomain(p))
	if err != nil {
		if isUniqueConstraintViolation(err) {
			return domain.ErrProjectKeyTaken
		}
		return apperror.Wrap(apperror.KindInternal, "failed to save project", err)
	}
	p.ID = id
	return nil
}

// CreateWithDefaults persists the project with its lead, the default board and the default
// workflow. It is CreateWithMembers without initial members or teams.
func (r *ProjectRepository) CreateWithDefaults(ctx context.Context, p *domain.Project, lead port.Member) error {
	return r.CreateWithMembers(ctx, p, lead, nil, nil)
}

// CreateWithMembers persists the project together with its lead, initial members (contributor),
// team grants (contributor) and the default board and workflow, all in one transaction. Team ids
// must belong to the project organization. Database ids are generated by the database, so the
// project is inserted first and the other rows use the returned id.
func (r *ProjectRepository) CreateWithMembers(ctx context.Context, p *domain.Project, lead port.Member, members []port.Member, teamIDs []uuid.UUID) error {
	tx, err := r.db.BeginTxx(ctx, nil)
	if err != nil {
		return apperror.Wrap(apperror.KindInternal, "failed to begin project creation", err)
	}
	defer func() { _ = tx.Rollback() }()

	projectID, err := database.InsertReturningID(ctx, tx, insertProjectQuery, fromDomain(p))
	if err != nil {
		if isUniqueConstraintViolation(err) {
			return domain.ErrProjectKeyTaken
		}
		return apperror.Wrap(apperror.KindInternal, "failed to save project", err)
	}
	p.ID = projectID
	lead.ProjectID = projectID

	if err := insertMember(ctx, tx, lead); err != nil {
		return err
	}
	for _, member := range members {
		member.ProjectID = projectID
		if err := insertMember(ctx, tx, member); err != nil {
			return err
		}
	}
	for _, teamID := range teamIDs {
		var inOrg bool
		if err := tx.GetContext(ctx, &inOrg, `
			SELECT EXISTS (SELECT 1 FROM teams WHERE id = $1 AND organization_id = $2)`, teamID, p.OrganizationID); err != nil {
			return apperror.Wrap(apperror.KindInternal, "failed to check team organization", err)
		}
		if !inOrg {
			return domain.ErrTeamNotInOrg
		}
		if _, err := tx.ExecContext(ctx, `
			INSERT INTO project_team_roles (project_id, team_id, role, created_at)
			VALUES ($1, $2, 'contributor', now())`, projectID, teamID); err != nil {
			return apperror.Wrap(apperror.KindInternal, "failed to grant team access", err)
		}
	}

	defaultBoard, err := boarddomain.NewDefaultBoard(p.ID, boarddomain.Type(p.Type))
	if err != nil {
		return err
	}
	boardID, err := database.InsertReturningID(ctx, tx, `
		INSERT INTO boards (project_id, name, type, config, is_default, created_at, updated_at)
		VALUES (:project_id, :name, :type, CAST(:config AS jsonb), :is_default, :created_at, :updated_at)
		RETURNING id`, boardRowArgs(defaultBoard))
	if err != nil {
		return apperror.Wrap(apperror.KindInternal, "failed to create default project board", err)
	}
	defaultBoard.ID = boardID

	for i := range defaultBoard.Columns {
		column := &defaultBoard.Columns[i]
		column.BoardID = boardID
		if _, err := tx.ExecContext(ctx, `
			INSERT INTO board_columns (board_id, name, status, position, wip_limit, created_at, updated_at)
			VALUES ($1, $2, $3, $4, $5, $6, $7)`,
			column.BoardID, column.Name, column.Status, column.Position,
			column.WIPLimit, column.CreatedAt, column.UpdatedAt); err != nil {
			return apperror.Wrap(apperror.KindInternal, "failed to create default board column", err)
		}
	}

	defaultWorkflowID, err := database.InsertReturningID(ctx, tx, `
		INSERT INTO workflows (project_id, name, is_default, created_at, updated_at)
		VALUES (:project_id, 'Default', true, now(), now())
		RETURNING id`, map[string]interface{}{"project_id": p.ID})
	if err != nil {
		return apperror.Wrap(apperror.KindInternal, "failed to create default project workflow", err)
	}
	for _, transition := range [][2]string{
		{"open", "in_progress"}, {"open", "closed"},
		{"in_progress", "resolved"}, {"in_progress", "closed"},
		{"resolved", "closed"}, {"resolved", "in_progress"},
	} {
		if _, err := tx.ExecContext(ctx, `
			INSERT INTO workflow_transitions (workflow_id, from_status, to_status, allowed_roles)
			VALUES ($1, $2, $3, 'admin,agent,requester')`, defaultWorkflowID, transition[0], transition[1]); err != nil {
			return apperror.Wrap(apperror.KindInternal, "failed to create default project workflow transition", err)
		}
	}
	if err := tx.Commit(); err != nil {
		return apperror.Wrap(apperror.KindInternal, "failed to commit project creation", err)
	}
	return nil
}

// insertMember adds a project member inside the creation transaction.
func insertMember(ctx context.Context, tx sqlx.ExtContext, member port.Member) error {
	if _, err := tx.ExecContext(ctx, `
		INSERT INTO project_members (project_id, user_id, role, created_at)
		VALUES ($1, $2, $3, $4)`, member.ProjectID, member.UserID, member.Role, member.CreatedAt); err != nil {
		if isForeignKeyViolation(err) {
			return domain.ErrUserNotFound
		}
		return apperror.Wrap(apperror.KindInternal, "failed to add project member", err)
	}
	return nil
}

// isUniqueConstraintViolation reports SQLSTATE 23505. On projects the unique constraints are the
// primary key and the partial index on (organization_id, key) over live rows, so a violation
// means the key is taken.
func isUniqueConstraintViolation(err error) bool {
	var pgErr *pgconn.PgError
	return errors.As(err, &pgErr) && pgErr.Code == "23505"
}

// isForeignKeyViolation reports SQLSTATE 23503.
func isForeignKeyViolation(err error) bool {
	var pgErr *pgconn.PgError
	return errors.As(err, &pgErr) && pgErr.Code == "23503"
}

// FindByID returns a live (not deleted) project.
func (r *ProjectRepository) FindByID(ctx context.Context, id uuid.UUID) (*domain.Project, error) {
	var row projectRow
	if err := sqlx.GetContext(ctx, r.exec(ctx), &row, `SELECT `+projectColumns+` FROM projects WHERE id = $1 AND deleted_at IS NULL`, id); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return nil, domain.ErrProjectNotFound
		}
		return nil, apperror.Wrap(apperror.KindInternal, "failed to find project", err)
	}
	return row.toDomain(), nil
}

// FindByKey busca una clave dentro de una organizacion entre los proyectos vivos.
func (r *ProjectRepository) FindByKey(ctx context.Context, orgID uuid.UUID, key string) (*domain.Project, error) {
	var row projectRow
	if err := sqlx.GetContext(ctx, r.exec(ctx), &row, `
		SELECT `+projectColumns+` FROM projects
		WHERE organization_id = $1 AND key = $2 AND deleted_at IS NULL`, orgID, domain.NormalizeKey(key)); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return nil, domain.ErrProjectNotFound
		}
		return nil, apperror.Wrap(apperror.KindInternal, "failed to find project", err)
	}
	return row.toDomain(), nil
}

// KeyAvailable reports whether no live project of the organization uses the key.
func (r *ProjectRepository) KeyAvailable(ctx context.Context, orgID uuid.UUID, key string) (bool, error) {
	var taken bool
	if err := sqlx.GetContext(ctx, r.exec(ctx), &taken, `
		SELECT EXISTS (SELECT 1 FROM projects
		               WHERE organization_id = $1 AND key = $2 AND deleted_at IS NULL)`, orgID, domain.NormalizeKey(key)); err != nil {
		return false, apperror.Wrap(apperror.KindInternal, "failed to check project key", err)
	}
	return !taken, nil
}

// AllocateIssueNumber takes the next number with one atomic UPDATE. The row lock serializes
// concurrent allocations, so every caller gets a distinct number.
func (r *ProjectRepository) AllocateIssueNumber(ctx context.Context, projectID uuid.UUID) (int, error) {
	var number int
	if err := sqlx.GetContext(ctx, r.exec(ctx), &number, `
		UPDATE projects
		SET next_issue_number = next_issue_number + 1
		WHERE id = $1 AND deleted_at IS NULL
		RETURNING next_issue_number - 1`, projectID); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return 0, domain.ErrProjectNotFound
		}
		return 0, apperror.Wrap(apperror.KindInternal, "failed to allocate issue number", err)
	}
	return number, nil
}

// FindByOrganization lista los proyectos vivos de la organizacion que el alcance permite ver.
// Los proyectos donde el usuario es miembro explicito, o miembro de un equipo con acceso, siempre
// se incluyen.
func (r *ProjectRepository) FindByOrganization(ctx context.Context, orgID uuid.UUID, scope port.VisibilityScope) ([]*domain.Project, error) {
	var rows []projectRow
	if err := sqlx.SelectContext(ctx, r.exec(ctx), &rows, `
		SELECT `+projectColumns+` FROM projects
		WHERE organization_id = $1
		  AND deleted_at IS NULL
		  AND ($2::boolean
		       OR id IN (SELECT pm.project_id FROM project_members pm WHERE pm.user_id = $3)
		       OR id IN (SELECT ptr.project_id FROM project_team_roles ptr
		                 JOIN team_members tm ON tm.team_id = ptr.team_id WHERE tm.user_id = $3)
		       OR ($4::boolean AND visibility = $5))
		ORDER BY name ASC`,
		orgID, scope.All, scope.UserID, scope.Open, storedOpen); err != nil {
		return nil, apperror.Wrap(apperror.KindInternal, "failed to list projects", err)
	}
	projects := make([]*domain.Project, 0, len(rows))
	for _, row := range rows {
		projects = append(projects, row.toDomain())
	}
	return projects, nil
}

// sortColumns maps the whitelisted sort fields to SQL columns. User input never reaches the SQL text.
var sortColumns = map[port.SortField]string{
	port.SortByName:      "name",
	port.SortByKey:       "key",
	port.SortByCreatedAt: "created_at",
	port.SortByUpdatedAt: "updated_at",
}

// ListPage returns one page of the filtered listing and the total number of matches.
func (r *ProjectRepository) ListPage(ctx context.Context, filter port.ProjectFilter) (port.ProjectPage, error) {
	var q filterBuilder
	q.add("organization_id = %s", filter.OrganizationID)
	q.raw("deleted_at IS NULL")
	if !filter.Scope.All {
		q.raw(fmt.Sprintf(`(%s::boolean
		    OR id IN (SELECT pm.project_id FROM project_members pm WHERE pm.user_id = %s)
		    OR id IN (SELECT ptr.project_id FROM project_team_roles ptr
		              JOIN team_members tm ON tm.team_id = ptr.team_id WHERE tm.user_id = %s)
		    OR (%s::boolean AND visibility = %s))`,
			q.arg(filter.Scope.All),
			q.arg(filter.Scope.UserID),
			q.arg(filter.Scope.UserID),
			q.arg(filter.Scope.Open),
			q.arg(storedOpen)))
	}
	if filter.Q != "" {
		pattern := "%" + escapeLike(filter.Q) + "%"
		q.raw(fmt.Sprintf(`(name ILIKE %s ESCAPE '\' OR key ILIKE %s ESCAPE '\')`, q.arg(pattern), q.arg(pattern)))
	}
	if filter.Template != "" {
		q.add("template = %s", string(filter.Template))
	}
	if filter.LeadID != nil {
		q.add("lead_id = %s", *filter.LeadID)
	}
	if filter.Starred {
		q.raw(fmt.Sprintf(`EXISTS (SELECT 1 FROM favorites f
		    WHERE f.user_id = %s AND f.entity_type = 'project' AND f.entity_id = projects.id)`, q.arg(filter.Scope.UserID)))
	}
	switch filter.Archived {
	case port.ArchiveFilterOnly:
		q.raw("archived_at IS NOT NULL")
	case port.ArchiveFilterExclude, "":
		q.raw("archived_at IS NULL")
	}

	where := q.where()
	var total int
	if err := sqlx.GetContext(ctx, r.exec(ctx), &total, `SELECT count(*) FROM projects WHERE `+where, q.args...); err != nil {
		return port.ProjectPage{}, apperror.Wrap(apperror.KindInternal, "failed to count projects", err)
	}

	column, ok := sortColumns[filter.Sort]
	if !ok {
		column = sortColumns[port.SortByName]
	}
	direction := "ASC"
	if filter.Desc {
		direction = "DESC"
	}
	limit := q.arg(filter.PageSize)
	offset := q.arg((filter.Page - 1) * filter.PageSize)
	var rows []projectRow
	if err := sqlx.SelectContext(ctx, r.exec(ctx), &rows, `
		SELECT `+projectColumns+` FROM projects
		WHERE `+where+`
		ORDER BY `+column+` `+direction+`, id ASC
		LIMIT `+limit+` OFFSET `+offset, q.args...); err != nil {
		return port.ProjectPage{}, apperror.Wrap(apperror.KindInternal, "failed to list projects", err)
	}
	items := make([]*domain.Project, 0, len(rows))
	for _, row := range rows {
		items = append(items, row.toDomain())
	}
	return port.ProjectPage{Items: items, Total: total}, nil
}

// filterBuilder assembles a WHERE clause with positional parameters.
type filterBuilder struct {
	clauses []string
	args    []any
}

// arg registers a value and returns its placeholder.
func (b *filterBuilder) arg(value any) string {
	b.args = append(b.args, value)
	return fmt.Sprintf("$%d", len(b.args))
}

// add appends a clause whose single %s is replaced by a placeholder for value.
func (b *filterBuilder) add(format string, value any) {
	b.raw(fmt.Sprintf(format, b.arg(value)))
}

// raw appends a finished clause.
func (b *filterBuilder) raw(clause string) {
	b.clauses = append(b.clauses, clause)
}

func (b *filterBuilder) where() string {
	return strings.Join(b.clauses, " AND ")
}

// escapeLike escapes the LIKE wildcards so user text matches literally.
func escapeLike(value string) string {
	replacer := strings.NewReplacer(`\`, `\\`, `%`, `\%`, `_`, `\_`)
	return replacer.Replace(value)
}

func (r *ProjectRepository) Update(ctx context.Context, p *domain.Project) error {
	row := fromDomain(p)
	const query = `
		UPDATE projects
		SET name = :name, description = :description, type = :type, template = :template,
		    lead_id = :lead_id, visibility = :visibility, color = :color, icon = :icon,
		    default_assignee_policy = :default_assignee_policy, archived_at = :archived_at,
		    updated_at = :updated_at
		WHERE id = :id AND organization_id = :organization_id AND deleted_at IS NULL`
	result, err := sqlx.NamedExecContext(ctx, r.exec(ctx), query, row)
	if err != nil {
		return apperror.Wrap(apperror.KindInternal, "failed to update project", err)
	}
	affected, err := result.RowsAffected()
	if err != nil {
		return apperror.Wrap(apperror.KindInternal, "failed to update project", err)
	}
	if affected == 0 {
		return domain.ErrProjectNotFound
	}
	return nil
}

// Delete soft deletes the project. Its row stays, reads stop seeing it, and its key is freed.
func (r *ProjectRepository) Delete(ctx context.Context, orgID, id uuid.UUID) error {
	result, err := r.exec(ctx).ExecContext(ctx, `
		UPDATE projects SET deleted_at = now(), updated_at = now()
		WHERE id = $1 AND organization_id = $2 AND deleted_at IS NULL`, id, orgID)
	if err != nil {
		return apperror.Wrap(apperror.KindInternal, "failed to delete project", err)
	}
	affected, err := result.RowsAffected()
	if err != nil {
		return apperror.Wrap(apperror.KindInternal, "failed to delete project", err)
	}
	if affected == 0 {
		return domain.ErrProjectNotFound
	}
	return nil
}

// boardRowArgs arma los parametros nombrados del INSERT de boards.
func boardRowArgs(b *boarddomain.Board) map[string]interface{} {
	return map[string]interface{}{
		"project_id": b.ProjectID,
		"name":       b.Name,
		"type":       b.Type,
		"config":     string(b.Config),
		"is_default": b.IsDefault,
		"created_at": b.CreatedAt,
		"updated_at": b.UpdatedAt,
	}
}
