const logoTestSecret = "logo-test-secret"

// logoFakeRoles mirrors OrgRoleChecker semantics: non-members get not_found, members below the minimum
// rank get forbidden.
type logoFakeRoles struct {
	members map[[2]uuid.UUID]string // [org, user] -> role
}

var logoRank = map[string]int{"guest": 1, "member": 2, "admin": 3, "owner": 4}

func (f *logoFakeRoles) RequireRole(_ context.Context, userID, orgID uuid.UUID, min string) error {
	role, ok := f.members[[2]uuid.UUID{orgID, userID}]
	if !ok {
		return apperror.WithCode(apperror.KindNotFound, "org.not_found", "Organización no encontrada")
	}
	if logoRank[role] < logoRank[min] {
		return apperror.WithCode(apperror.KindForbidden, "org.forbidden", "No tienes permiso")
	}
	return nil
}

type logoFakeRepo struct {
	keys map[uuid.UUID]string
}

func (r *logoFakeRepo) SetLogoKey(_ context.Context, orgID uuid.UUID, key *string) (*string, error) {
	old, had := r.keys[orgID]
	if key == nil {
		delete(r.keys, orgID)
	} else {
		r.keys[orgID] = *key
	}
	if !had {
		return nil, nil
	}
	return &old, nil
}

func (r *logoFakeRepo) GetLogoKey(_ context.Context, orgID uuid.UUID) (*string, error) {
	k, ok := r.keys[orgID]
	if !ok {
		return nil, nil
	}
	return &k, nil
}

type logoEnv struct {
	router *chi.Mux
	repo   *logoFakeRepo
	files  *filestorage.DiskStorage
	roles  *logoFakeRoles
	org    uuid.UUID
	owner  string
	admin  string
	member string
	guest  string
	nobody string
}

func newLogoEnv(t *testing.T) *logoEnv {
	t.Helper()
	env := &logoEnv{
		repo:  &logoFakeRepo{keys: map[uuid.UUID]string{}},
		files: filestorage.NewDiskStorage(filepath.Join(t.TempDir(), "logos")),
		roles: &logoFakeRoles{members: map[[2]uuid.UUID]string{}},
		org:   uuid.New(),
	}
	mk := func(role string) string {
		id := uuid.New()
		env.roles.members[[2]uuid.UUID{env.org, id}] = role
		tok, err := authtoken.Generate(logoTestSecret, time.Hour, id, "user")
		if err != nil {
			t.Fatal(err)
		}
		return tok
	}
	env.owner = mk("owner")
	env.admin = mk("admin")
	env.member = mk("member")
	env.guest = mk("guest")
	env.nobody = mk("member") // member of a different organization, see below
	delete(env.roles.members, [2]uuid.UUID{env.org, mustUserID(t, env.nobody)})

	env.router = chi.NewRouter()
	NewLogoHandler(env.repo, env.files, env.roles, logoTestSecret).RegisterRoutes(env.router)
	return env
}

// mustUserID extracts the subject of a token generated by newLogoEnv.
func mustUserID(t *testing.T, token string) uuid.UUID {
	t.Helper()
	claims, err := authtoken.Parse(logoTestSecret, token)
	if err != nil {
		t.Fatal(err)
	}
	return claims.UserID
}

func logoPNG(t *testing.T, w, h int) []byte {
	t.Helper()
	img := image.NewNRGBA(image.Rect(0, 0, w, h))
	for x := 0; x < w; x++ {
		img.Set(x, 0, color.NRGBA{0, 128, 255, 255})
	}
	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func logoMultipart(t *testing.T, field, contentType string, data []byte) (*bytes.Buffer, string) {
	t.Helper()
	var buf bytes.Buffer
	mw := multipart.NewWriter(&buf)
	h := map[string][]string{"Content-Disposition": {`form-data; name="` + field + `"; filename="logo.bin"`}}
	if contentType != "" {
		h["Content-Type"] = []string{contentType}
	}
	part, err := mw.CreatePart(h)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := part.Write(data); err != nil {
		t.Fatal(err)
	}
	if err := mw.Close(); err != nil {
		t.Fatal(err)
	}
	return &buf, mw.FormDataContentType()
}

func (env *logoEnv) do(method, path, token string, body *bytes.Buffer, contentType string, headers map[string]string) *httptest.ResponseRecorder {
	if body == nil {
		body = &bytes.Buffer{}
	}
	req := httptest.NewRequest(method, path, body)
	if contentType != "" {
		req.Header.Set("Content-Type", contentType)
	}
	if token != "" {
		req.Header.Set("Authorization", "Bearer "+token)
	}
	for k, v := range headers {
		req.Header.Set(k, v)
	}
	rec := httptest.NewRecorder()
	env.router.ServeHTTP(rec, req)
	return rec
}

func (env *logoEnv) path() string {
	return "/organizations/" + env.org.String() + "/logo"
}

func (env *logoEnv) upload(t *testing.T, token string, data []byte, declared string) *httptest.ResponseRecorder {
	t.Helper()
	body, ct := logoMultipart(t, "file", declared, data)
	return env.do(http.MethodPut, env.path(), token, body, ct, nil)
}

func logoErrorCode(t *testing.T, rec *httptest.ResponseRecorder) string {
	t.Helper()
	var body struct {
		Error struct {
			Code string `json:"code"`
		} `json:"error"`
	}
	if err := json.Unmarshal(rec.Body.Bytes(), &body); err != nil {
		t.Fatalf("decode error body %q: %v", rec.Body.String(), err)
	}
	return body.Error.Code
}

func TestLogoRequiresAuthentication(t *testing.T) {
	env := newLogoEnv(t)
	for _, method := range []string{http.MethodPut, http.MethodDelete, http.MethodGet} {
		if rec := env.do(method, env.path(), "", nil, "", nil); rec.Code != http.StatusUnauthorized {
			t.Errorf("%s without token = %d, want 401", method, rec.Code)
		}
	}
}

func TestLogoUploadPermissions(t *testing.T) {
	env := newLogoEnv(t)
	data := logoPNG(t, 300, 200)

	if rec := env.upload(t, env.owner, data, "image/png"); rec.Code != http.StatusOK {
		t.Fatalf("owner upload = %d %s", rec.Code, rec.Body.String())
	}
	if rec := env.upload(t, env.admin, data, "image/png"); rec.Code != http.StatusOK {
		t.Fatalf("admin upload = %d", rec.Code)
	}
	rec := env.upload(t, env.member, data, "image/png")
	if rec.Code != http.StatusForbidden {
		t.Fatalf("member upload = %d, want 403", rec.Code)
	}
	rec = env.upload(t, env.guest, data, "image/png")
	if rec.Code != http.StatusForbidden {
		t.Fatalf("guest upload = %d, want 403", rec.Code)
	}
	rec = env.upload(t, env.nobody, data, "image/png")
	if rec.Code != http.StatusNotFound {
		t.Fatalf("non-member upload = %d, want 404", rec.Code)
	}
	if rec := env.do(http.MethodDelete, env.path(), env.member, nil, "", nil); rec.Code != http.StatusForbidden {
		t.Fatalf("member delete = %d, want 403", rec.Code)
	}
	if rec := env.do(http.MethodDelete, env.path(), env.nobody, nil, "", nil); rec.Code != http.StatusNotFound {
		t.Fatalf("non-member delete = %d, want 404", rec.Code)
	}
}

func TestLogoUploadReplaceAndDelete(t *testing.T) {
	env := newLogoEnv(t)

	if rec := env.upload(t, env.owner, logoPNG(t, 64, 64), "image/png"); rec.Code != http.StatusOK {
		t.Fatalf("upload = %d", rec.Code)
	}
	first := env.repo.keys[env.org]
	if rec := env.upload(t, env.admin, logoPNG(t, 128, 32), "image/png"); rec.Code != http.StatusOK {
		t.Fatalf("replace = %d", rec.Code)
	}
	second := env.repo.keys[env.org]
	if second == "" || second == first {
		t.Fatal("replace must store a new key")
	}
	if _, err := env.files.Stat(context.Background(), first); err == nil {
		t.Fatal("old logo file must be removed")
	}

	if rec := env.do(http.MethodDelete, env.path(), env.admin, nil, "", nil); rec.Code != http.StatusNoContent {
		t.Fatalf("delete = %d", rec.Code)
	}
	if _, ok := env.repo.keys[env.org]; ok {
		t.Fatal("logo key must be cleared")
	}
	if _, err := env.files.Stat(context.Background(), second); err == nil {
		t.Fatal("deleted logo file must be removed")
	}
	if rec := env.do(http.MethodDelete, env.path(), env.owner, nil, "", nil); rec.Code != http.StatusNoContent {
		t.Fatalf("second delete = %d, want idempotent 204", rec.Code)
	}
}

func TestLogoUploadRejections(t *testing.T) {
	env := newLogoEnv(t)

	cases := []struct {
		name   string
		data   []byte
		status int
		code   string
	}{
		{"text declared as png", []byte("no soy una imagen"), http.StatusUnprocessableEntity, "org.logo_invalid"},
		{"dimension bomb", logoPNG(t, 4097, 1), http.StatusUnprocessableEntity, "org.logo_invalid"},
		{"oversize", make([]byte, 2<<20+1), http.StatusRequestEntityTooLarge, "org.logo_too_large"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			rec := env.upload(t, env.owner, tc.data, "image/png")
			if rec.Code != tc.status {
				t.Fatalf("status = %d, want %d: %s", rec.Code, tc.status, rec.Body.String())
			}
			if code := logoErrorCode(t, rec); code != tc.code {
				t.Fatalf("code = %q, want %q", code, tc.code)
			}
		})
	}

	t.Run("missing file field", func(t *testing.T) {
		body, ct := logoMultipart(t, "otro", "image/png", logoPNG(t, 8, 8))
		rec := env.do(http.MethodPut, env.path(), env.owner, body, ct, nil)
		if rec.Code != http.StatusUnprocessableEntity || logoErrorCode(t, rec) != "org.logo_invalid" {
			t.Fatalf("got %d %s", rec.Code, rec.Body.String())
		}
	})
	t.Run("invalid organization id", func(t *testing.T) {
		rec := env.do(http.MethodPut, "/organizations/no-es-uuid/logo", env.owner, nil, "", nil)
		if rec.Code != http.StatusUnprocessableEntity {
			t.Fatalf("got %d", rec.Code)
		}
	})

	if _, ok := env.repo.keys[env.org]; ok {
		t.Fatal("rejected uploads must not set a logo")
	}
}

func TestLogoGetMembersAndCacheHeaders(t *testing.T) {
	env := newLogoEnv(t)
	if rec := env.upload(t, env.owner, logoPNG(t, 50, 70), "image/png"); rec.Code != http.StatusOK {
		t.Fatalf("upload = %d", rec.Code)
	}

	for name, token := range map[string]string{"owner": env.owner, "member": env.member, "guest": env.guest} {
		rec := env.do(http.MethodGet, env.path(), token, nil, "", nil)
		if rec.Code != http.StatusOK {
			t.Fatalf("%s get = %d", name, rec.Code)
		}
	}

	rec := env.do(http.MethodGet, env.path(), env.member, nil, "", nil)
	if ct := rec.Header().Get("Content-Type"); ct != "image/png" {
		t.Errorf("Content-Type = %q", ct)
	}
	if cc := rec.Header().Get("Cache-Control"); cc != "private, max-age=3600" {
		t.Errorf("Cache-Control = %q", cc)
	}
	if xcto := rec.Header().Get("X-Content-Type-Options"); xcto != "nosniff" {
		t.Errorf("X-Content-Type-Options = %q", xcto)
	}
	etag := rec.Header().Get("ETag")
	if etag == "" || strings.Contains(etag, env.repo.keys[env.org]) {
		t.Fatalf("ETag = %q must be set and must not expose the storage key", etag)
	}
	if _, err := png.Decode(rec.Body); err != nil {
		t.Fatalf("body is not a PNG: %v", err)
	}

	rec = env.do(http.MethodGet, env.path(), env.member, nil, "", map[string]string{"If-None-Match": etag})
	if rec.Code != http.StatusNotModified || rec.Body.Len() != 0 {
		t.Fatalf("conditional get = %d body=%d, want empty 304", rec.Code, rec.Body.Len())
	}
}

func TestLogoGetNotMemberNotFoundAndNoLogo(t *testing.T) {
	env := newLogoEnv(t)

	if rec := env.do(http.MethodGet, env.path(), env.nobody, nil, "", nil); rec.Code != http.StatusNotFound {
		t.Fatalf("non-member get = %d, want 404", rec.Code)
	}
	rec := env.do(http.MethodGet, env.path(), env.member, nil, "", nil)
	if rec.Code != http.StatusNotFound || logoErrorCode(t, rec) != "org.logo_not_found" {
		t.Fatalf("no logo = %d %s", rec.Code, rec.Body.String())
	}
}

func TestLogoRoutesCoexistWithOrganizationRoutes(t *testing.T) {
	// The logo routes use full paths. Registering them next to other organization routes on the same
	// root router must not panic and must still reach the logo handler.
	env := newLogoEnv(t)
	root := chi.NewRouter()
	root.Route("/organizations/{org}/other", func(r chi.Router) {
		r.Get("/", func(w http.ResponseWriter, _ *http.Request) { w.WriteHeader(http.StatusTeapot) })
	})
	NewLogoHandler(env.repo, env.files, env.roles, logoTestSecret).RegisterRoutes(root)

	rec := env.do(http.MethodGet, env.path(), env.member, nil, "", nil)
	if rec.Code != http.StatusNotFound || logoErrorCode(t, rec) != "org.logo_not_found" {
		t.Fatalf("logo route not reached: %d %s", rec.Code, rec.Body.String())
	}
}
